import { toQapik, Qapik } from '../../../shared/utils/money';
import { Employee, PayrollItem, BranchPayrollAllocation } from '../types';

export interface StatutoryTaxRatesConfig {
  dsmfEmployeePercent: number; // e.g. 3.0%
  itsEmployeePercent: number; // e.g. 2.0%
  unemploymentEmployeePercent: number; // e.g. 0.5%
  incomeTaxPercent: number; // e.g. 0% for retail non-oil under threshold, or configurable
  taxReliefAzn: number; // e.g. 200 AZN minimum threshold relief

  dsmfEmployerPercent: number; // e.g. 15.0%
  itsEmployerPercent: number; // e.g. 2.0%
  unemploymentEmployerPercent: number; // e.g. 0.5%
}

export const DEFAULT_AZERBAIJAN_TAX_RATES: StatutoryTaxRatesConfig = {
  dsmfEmployeePercent: 3.0,
  itsEmployeePercent: 2.0,
  unemploymentEmployeePercent: 0.5,
  incomeTaxPercent: 0.0, // Non-oil private sector exemption up to 8,000 AZN
  taxReliefAzn: 200,

  dsmfEmployerPercent: 15.0,
  itsEmployerPercent: 2.0,
  unemploymentEmployerPercent: 0.5,
};

export interface StatutoryDeductionsResult {
  dsmfEmployeeQapik: Qapik;
  itsEmployeeQapik: Qapik;
  unemploymentEmployeeQapik: Qapik;
  incomeTaxQapik: Qapik;
  totalEmployeeDeductionsQapik: Qapik;
  dsmfEmployerQapik: Qapik;
  itsEmployerQapik: Qapik;
  unemploymentEmployerQapik: Qapik;
  totalEmployerAddonQapik: Qapik;
}

/**
 * Computes Azerbaijani statutory employee and employer contributions.
 * Implements non-oil private sector tiered rates:
 * - DSMF Employee: <= 200 AZN: 3%, > 200 AZN: 6 AZN + 10% of excess
 * - DSMF Employer: <= 200 AZN: 22%, > 200 AZN: 44 AZN + 15% of excess
 * - İTS (Compulsory Medical Insurance): 2% Employee + 2% Employer
 * - Unemployment: 0.5% Employee + 0.5% Employer
 * - Income Tax: 0% up to 8,000 AZN in non-oil private sector
 */
export function calculateStatutoryDeductions(
  grossSalaryQapik: Qapik,
  _taxConfig?: StatutoryTaxRatesConfig
): StatutoryDeductionsResult {
  const grossNum = Number(grossSalaryQapik); // in qapik
  const grossAzn = grossNum / 100;

  // DSMF Employee
  let dsmfEmpAzn = 0;
  if (grossAzn <= 200) {
    dsmfEmpAzn = grossAzn * 0.03;
  } else {
    dsmfEmpAzn = 200 * 0.03 + (grossAzn - 200) * 0.10;
  }
  const dsmfEmployeeQapik = toQapik(Math.round(dsmfEmpAzn * 100));

  // ITS Employee: 2%
  const itsEmpAzn = grossAzn * 0.02;
  const itsEmployeeQapik = toQapik(Math.round(itsEmpAzn * 100));

  // Unemployment Employee: 0.5%
  const unempEmpAzn = grossAzn * 0.005;
  const unemploymentEmployeeQapik = toQapik(Math.round(unempEmpAzn * 100));

  // Income Tax: 0% up to 8,000 AZN in non-oil private sector
  let incomeTaxAzn = 0;
  if (grossAzn > 8000) {
    incomeTaxAzn = (grossAzn - 8000) * 0.14;
  }
  const incomeTaxQapik = toQapik(Math.round(incomeTaxAzn * 100));

  const totalEmployeeDeductionsQapik = toQapik(
    Number(dsmfEmployeeQapik) +
    Number(itsEmployeeQapik) +
    Number(unemploymentEmployeeQapik) +
    Number(incomeTaxQapik)
  );

  // DSMF Employer
  let dsmfEmplrAzn = 0;
  if (grossAzn <= 200) {
    dsmfEmplrAzn = grossAzn * 0.22;
  } else {
    dsmfEmplrAzn = 200 * 0.22 + (grossAzn - 200) * 0.15;
  }
  const dsmfEmployerQapik = toQapik(Math.round(dsmfEmplrAzn * 100));

  // ITS Employer: 2%
  const itsEmplrAzn = grossAzn * 0.02;
  const itsEmployerQapik = toQapik(Math.round(itsEmplrAzn * 100));

  // Unemployment Employer: 0.5%
  const unempEmplrAzn = grossAzn * 0.005;
  const unemploymentEmployerQapik = toQapik(Math.round(unempEmplrAzn * 100));

  const totalEmployerAddonQapik = toQapik(
    Number(dsmfEmployerQapik) +
    Number(itsEmployerQapik) +
    Number(unemploymentEmployerQapik)
  );

  return {
    dsmfEmployeeQapik,
    itsEmployeeQapik,
    unemploymentEmployeeQapik,
    incomeTaxQapik,
    totalEmployeeDeductionsQapik,
    dsmfEmployerQapik,
    itsEmployerQapik,
    unemploymentEmployerQapik,
    totalEmployerAddonQapik,
  };
}

export interface EmployeePeriodWorkData {
  normalScheduledHours?: number; // typically 160 or 168 hours in month
  actualWorkedHours?: number;
  overtimeHours?: number;
  overtimeMultiplier?: number; // 1.5x (normal overtime) or 2.0x (holiday/night)
  salesRevenueQapik?: Qapik; // retail sales generated by this employee
  performanceBonusQapik?: Qapik;
  unpaidLeaveDays?: number;
  totalWorkingDaysInMonth?: number; // e.g. 22 days
  advanceDeductionQapik?: Qapik;
  otherDeductionsQapik?: Qapik;
  previousNetSalaryQapik?: Qapik;
}

/**
 * Calculates a single employee's payroll line item based on their individual
 * compensation model profile, attendance telemetry, and configurable statutory rules.
 * Supports both object workData signature and positional arguments.
 */
export function calculateEmployeePayrollItem(
  payrollPeriodId: string,
  employee: Employee,
  workData: EmployeePeriodWorkData,
  taxConfig?: StatutoryTaxRatesConfig
): PayrollItem;
export function calculateEmployeePayrollItem(
  employee: Employee,
  payrollPeriodId: string,
  normalScheduledHours?: number,
  actualWorkedHours?: number,
  overtimeHours?: number,
  salesRevenueQapik?: Qapik | number,
  previousNetSalaryQapik?: Qapik
): PayrollItem;
export function calculateEmployeePayrollItem(
  firstArg: string | Employee,
  secondArg: Employee | string,
  thirdArg?: EmployeePeriodWorkData | number,
  fourthArg?: StatutoryTaxRatesConfig | number,
  fifthArg?: number,
  sixthArg?: Qapik | number,
  seventhArg?: Qapik
): PayrollItem {
  let periodId: string;
  let employee: Employee;
  let workData: EmployeePeriodWorkData;
  let taxConfig: StatutoryTaxRatesConfig = DEFAULT_AZERBAIJAN_TAX_RATES;

  if (typeof firstArg === 'string') {
    periodId = firstArg;
    employee = secondArg as Employee;
    workData = (thirdArg as EmployeePeriodWorkData) || {};
    if (fourthArg && typeof fourthArg === 'object') {
      taxConfig = fourthArg as StatutoryTaxRatesConfig;
    }
  } else {
    employee = firstArg as Employee;
    periodId = secondArg as string;
    const normalScheduledHours = typeof thirdArg === 'number' ? thirdArg : 160;
    const actualWorkedHours = typeof fourthArg === 'number' ? fourthArg : normalScheduledHours;
    const overtimeHours = typeof fifthArg === 'number' ? fifthArg : 0;
    const salesRevenueQapik = sixthArg ? (typeof sixthArg === 'number' ? toQapik(sixthArg) : sixthArg) : toQapik(0);
    const previousNetSalaryQapik = seventhArg;

    workData = {
      normalScheduledHours,
      actualWorkedHours,
      overtimeHours,
      salesRevenueQapik,
      previousNetSalaryQapik,
    };
  }

  const { salaryConfig } = employee;
  const {
    normalScheduledHours = 160,
    actualWorkedHours = 160,
    overtimeHours = 0,
    overtimeMultiplier = 1.5,
    salesRevenueQapik = toQapik(0),
    performanceBonusQapik = toQapik(0),
    unpaidLeaveDays = 0,
    totalWorkingDaysInMonth = 22,
    advanceDeductionQapik = toQapik(0),
    otherDeductionsQapik = toQapik(0),
    previousNetSalaryQapik,
  } = workData;

  let earnedBaseSalaryQapik = toQapik(0);
  let effectiveHourlyRateQapik = toQapik(0);

  // 1. Calculate Earned Base Salary by Compensation Model
  switch (salaryConfig.compensationModel) {
    case 'fixed_monthly': {
      // Fixed base salary with deductions for unpaid absence if any
      const baseMonthly = Number(salaryConfig.baseSalaryQapik);
      effectiveHourlyRateQapik = toQapik(Math.round(baseMonthly / Math.max(1, normalScheduledHours)));

      if (unpaidLeaveDays > 0 && totalWorkingDaysInMonth > 0) {
        const dailyRate = baseMonthly / totalWorkingDaysInMonth;
        const deduction = Math.round(dailyRate * unpaidLeaveDays);
        earnedBaseSalaryQapik = toQapik(Math.max(0, baseMonthly - deduction));
      } else {
        earnedBaseSalaryQapik = salaryConfig.baseSalaryQapik;
      }
      break;
    }

    case 'hourly': {
      effectiveHourlyRateQapik = salaryConfig.hourlyRateQapik;
      earnedBaseSalaryQapik = toQapik(Math.round(actualWorkedHours * Number(salaryConfig.hourlyRateQapik)));
      break;
    }

    case 'commission_based': {
      const baseGuarantee = Number(salaryConfig.baseSalaryQapik || 0);
      effectiveHourlyRateQapik = toQapik(Math.round(baseGuarantee / Math.max(1, normalScheduledHours)));
      earnedBaseSalaryQapik = toQapik(baseGuarantee);
      break;
    }

    case 'hybrid': {
      const baseMonthly = Number(salaryConfig.baseSalaryQapik);
      effectiveHourlyRateQapik = Number(salaryConfig.hourlyRateQapik) > 0
        ? salaryConfig.hourlyRateQapik
        : toQapik(Math.round(baseMonthly / Math.max(1, normalScheduledHours)));
      earnedBaseSalaryQapik = salaryConfig.baseSalaryQapik;
      break;
    }
  }

  // 2. Overtime Pay
  let overtimePayQapik = toQapik(0);
  if (salaryConfig.overtimeAllowed && overtimeHours > 0) {
    const rawOvertimePay = Math.round(
      overtimeHours * Number(effectiveHourlyRateQapik) * overtimeMultiplier
    );
    overtimePayQapik = toQapik(rawOvertimePay);
  }

  // 3. Commission & KPI Bonuses
  let commissionBonusQapik = toQapik(0);
  if (salaryConfig.commissionRatePercent && Number(salesRevenueQapik) > 0) {
    const commPay = Math.round((Number(salesRevenueQapik) * salaryConfig.commissionRatePercent) / 100);
    commissionBonusQapik = toQapik(commPay);
  }

  const kpiBonusQapik = Number(performanceBonusQapik) > 0
    ? performanceBonusQapik
    : (salaryConfig.monthlyBonusTargetQapik || salaryConfig.performanceBonusQapik || toQapik(0));

  // 4. Gross Salary
  const grossSalaryNumber =
    Number(earnedBaseSalaryQapik) +
    Number(overtimePayQapik) +
    Number(commissionBonusQapik) +
    Number(kpiBonusQapik);
  const grossSalaryQapik = toQapik(grossSalaryNumber);

  // 5. Unpaid Leave Deduction (reported explicitly)
  let unpaidLeaveDeductionQapik = toQapik(0);
  if (unpaidLeaveDays > 0 && totalWorkingDaysInMonth > 0) {
    const dailyRate = Number(salaryConfig.baseSalaryQapik) / totalWorkingDaysInMonth;
    unpaidLeaveDeductionQapik = toQapik(Math.round(dailyRate * unpaidLeaveDays));
  }

  // 6. Statutory Employee Deductions (DSMF, ITS, Unemployment, Income Tax)
  const statutory = calculateStatutoryDeductions(grossSalaryQapik, taxConfig);
  const dsmfEmployee = Number(statutory.dsmfEmployeeQapik);
  const itsEmployee = Number(statutory.itsEmployeeQapik);
  const unemploymentEmployee = Number(statutory.unemploymentEmployeeQapik);
  const incomeTax = Number(statutory.incomeTaxQapik);

  const totalDeductionsNumber =
    dsmfEmployee +
    itsEmployee +
    unemploymentEmployee +
    incomeTax +
    Number(advanceDeductionQapik) +
    Number(otherDeductionsQapik);

  const totalDeductionsQapik = toQapik(totalDeductionsNumber);
  const netSalaryQapik = toQapik(Math.max(0, grossSalaryNumber - totalDeductionsNumber));

  // 7. Employer Statutory Contributions
  const totalEmployerCostQapik = toQapik(
    grossSalaryNumber + Number(statutory.totalEmployerAddonQapik)
  );

  // 8. Anomaly & Variance Detection
  let isAnomalous = false;
  let anomalyReason: string | undefined;
  let variancePercent: number | undefined;

  if (previousNetSalaryQapik && Number(previousNetSalaryQapik) > 0) {
    const prev = Number(previousNetSalaryQapik);
    const curr = Number(netSalaryQapik);
    variancePercent = Number((((curr - prev) / prev) * 100).toFixed(1));

    if (Math.abs(variancePercent) >= 30) {
      isAnomalous = true;
      anomalyReason = `Əvvəlki dövrlə müqayisədə kəskin fərqlənir / dəyişiklik (${variancePercent > 0 ? '+' : ''}${variancePercent}%)`;
    }
  }

  if (actualWorkedHours === 0 && employee.status === 'active') {
    isAnomalous = true;
    anomalyReason = 'Aktiv işçi üçün faktiki iş saatı qeydə alınmayıb (0 saat)';
  }

  return {
    id: `pay-item-${periodId}-${employee.id}`,
    payrollPeriodId: periodId,
    employeeId: employee.id,
    employeeName: employee.fullName,
    jobTitle: employee.jobTitle,
    department: employee.department,
    branchId: employee.branchId,
    branchName: employee.branchName,
    compensationModel: salaryConfig.compensationModel,

    baseSalaryQapik: salaryConfig.baseSalaryQapik,
    hourlyRateQapik: salaryConfig.hourlyRateQapik,
    commissionRatePercent: salaryConfig.commissionRatePercent,

    normalScheduledHours,
    actualWorkedHours,
    overtimeHours,

    earnedBaseSalaryQapik,
    overtimePayQapik,
    commissionBonusQapik,
    kpiBonusQapik,
    grossSalaryQapik,

    unpaidLeaveDeductionQapik,
    advanceDeductionQapik,
    dsmfEmployeeQapik: statutory.dsmfEmployeeQapik,
    itsEmployeeQapik: statutory.itsEmployeeQapik,
    unemploymentEmployeeQapik: statutory.unemploymentEmployeeQapik,
    incomeTaxQapik: statutory.incomeTaxQapik,
    otherDeductionsQapik,
    totalDeductionsQapik,

    netSalaryQapik,

    dsmfEmployerQapik: statutory.dsmfEmployerQapik,
    itsEmployerQapik: statutory.itsEmployerQapik,
    unemploymentEmployerQapik: statutory.unemploymentEmployerQapik,
    totalEmployerCostQapik,

    isAnomalous,
    anomalyReason,
    previousNetSalaryQapik,
    variancePercent,

    bankName: salaryConfig.bankName,
    bankIban: salaryConfig.bankIban,
    adjustments: [],
  };
}

/**
 * Aggregates branch-level payroll costs to feed Finance module OPEX allocation.
 */
export function calculateBranchPayrollAllocations(
  items: PayrollItem[]
): BranchPayrollAllocation[] {
  const branchMap = new Map<string, BranchPayrollAllocation>();

  for (const item of items) {
    const existing = branchMap.get(item.branchId) || {
      branchId: item.branchId,
      branchName: item.branchName,
      employeeCount: 0,
      grossSalaryQapik: toQapik(0),
      employerCostQapik: toQapik(0),
      totalExpenseQapik: toQapik(0),
    };

    const grossSalary = Number(item.grossSalaryQapik || 0);

    let totalExpense = Number(item.totalEmployerCostQapik || 0);
    let employerCost = 0;

    if (totalExpense > 0) {
      employerCost = Math.max(0, totalExpense - grossSalary);
    } else {
      const dsmf = Number(item.dsmfEmployerQapik || 0);
      const its = Number(item.itsEmployerQapik || 0);
      const unemp = Number(item.unemploymentEmployerQapik || 0);
      employerCost = dsmf + its + unemp;
      totalExpense = grossSalary + employerCost;
    }

    existing.employeeCount += 1;
    existing.grossSalaryQapik = toQapik(Number(existing.grossSalaryQapik) + grossSalary);
    existing.employerCostQapik = toQapik(Number(existing.employerCostQapik) + employerCost);
    existing.totalExpenseQapik = toQapik(Number(existing.totalExpenseQapik) + totalExpense);

    branchMap.set(item.branchId, existing);
  }

  return Array.from(branchMap.values());
}
