"""Mərkəzi Hesabatlar Reyestri (Report Registry).

Sistemdəki bütün 61 hesabatın metadatasını, icazə tələblərini, icazə verilən filtrlərini
və sütun konfiqurasiyalarını özündə saxlayır.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ReportColumn:
    key: str
    az_label: str
    type: str  # string, number, decimal, date, datetime, percent, boolean
    format: str | None = None  # e.g. "0.00 AZN", "YYYY-MM-DD", "0.0%"
    sortable: bool = True
    masked_by_permission: str | None = None  # e.g. "reports.cost.view", "hr.salary.view"


@dataclass(frozen=True)
class DrillDownLink:
    target_report_id: str
    filter_mapping: dict[str, str]  # e.g. {"branch_id": "branch_id", "date": "date_from"}


@dataclass(frozen=True)
class ReportDefinition:
    id: str
    az_title: str
    module: str
    description: str
    required_permissions: list[str]
    allowed_filters: list[str]
    columns: list[ReportColumn]
    default_sort: str = "date DESC"
    drill_down_links: list[DrillDownLink] = field(default_factory=list)


